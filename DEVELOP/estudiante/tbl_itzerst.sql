
CREATE TABLE INTEGRACION.ITZERST (
    ID               NUMBER(19,0) NOT NULL,
    TERM_CODE        VARCHAR2(6 BYTE),
    PIDM             NUMBER,
    CRN              VARCHAR2(5 BYTE),
    BUSINESS_LINE    VARCHAR2(50 BYTE),
    REQUEST          CLOB,
    RESPONSE         CLOB,
    CREATE_DATE      TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
    REQUEST_DATE     TIMESTAMP(6),
    RESPONSE_DATE    TIMESTAMP(6),
    OP_TYPE          VARCHAR2(100 BYTE),
    STATUS           VARCHAR2(100 BYTE),
    STATUS_RESPONSE  VARCHAR2(100 BYTE),

    CONSTRAINT PK_ITZERST PRIMARY KEY (ID)
);


     GRANT SELECT, INSERT, UPDATE, DELETE ON INTEGRACION.ITZERST TO PUBLIC;


CREATE PUBLIC SYNONYM ITZERST FOR integracion.ITZERST;

CREATE SEQUENCE INTEGRACION.SEQ_ITZERST
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

COMMENT ON TABLE INTEGRACION.ITZERST IS
'Integración de inscripciones de alumnos';

COMMENT ON COLUMN INTEGRACION.ITZERST.ID IS
'Identificador secuencial autogenerado';

COMMENT ON COLUMN INTEGRACION.ITZERST.TERM_CODE IS
'Periodo académico Banner';

COMMENT ON COLUMN INTEGRACION.ITZERST.PIDM IS
'Identificador interno de persona Banner';

COMMENT ON COLUMN INTEGRACION.ITZERST.CRN IS
'Número de referencia del curso (NRC)';

COMMENT ON COLUMN INTEGRACION.ITZERST.BUSINESS_LINE IS
'Línea de negocio: ONLINE, FLEX o CYP';

COMMENT ON COLUMN INTEGRACION.ITZERST.REQUEST IS
'JSON enviado al servicio';

COMMENT ON COLUMN INTEGRACION.ITZERST.RESPONSE IS
'JSON recibido como respuesta del servicio';

COMMENT ON COLUMN INTEGRACION.ITZERST.CREATE_DATE IS
'Fecha de creación del registro';

COMMENT ON COLUMN INTEGRACION.ITZERST.REQUEST_DATE IS
'Fecha y hora de envío de la solicitud';

COMMENT ON COLUMN INTEGRACION.ITZERST.RESPONSE_DATE IS
'Fecha y hora de recepción de la respuesta';

COMMENT ON COLUMN INTEGRACION.ITZERST.OP_TYPE IS
'Tipo de operación: CREATE_ENRROLLMENT';

COMMENT ON COLUMN INTEGRACION.ITZERST.STATUS IS
'Estado: PENDING, PROCESSING, PROCESSED, COMPLETED, FAIL';

COMMENT ON COLUMN INTEGRACION.ITZERST.STATUS_RESPONSE IS
'Estado de procesamiento de la respuesta en Banner';