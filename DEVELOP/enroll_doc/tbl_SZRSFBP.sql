CREATE TABLE integracion.SZRSFBP (
    SZRSFBP_TERM_CODE      VARCHAR2(6)  NOT NULL,
    SZRSFBP_PIDM           NUMBER(8)    NOT NULL,
    SZRSFBP_CRN            VARCHAR2(5)  NOT NULL,
    SZRSFBP_ACTIVITY_DATE  DATE         DEFAULT SYSDATE NOT NULL,
    SZRSFBP_SURROGATE_ID   NUMBER(19)   NOT NULL,

    CONSTRAINT PK_SZRSFBP
        PRIMARY KEY (SZRSFBP_SURROGATE_ID)
);

GRANT SELECT, INSERT, DELETE, UPDATE ON integracion.SZRSFBP TO PUBLIC

CREATE SEQUENCE SZRSFBP_SURROGATE_ID_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE OR REPLACE TRIGGER BI_SZRSFBP
BEFORE INSERT ON integracion.SZRSFBP
FOR EACH ROW
BEGIN
    IF :NEW.SZRSFBP_SURROGATE_ID IS NULL THEN
        SELECT SZRSFBP_SURROGATE_ID_SEQ.NEXTVAL
          INTO :NEW.SZRSFBP_SURROGATE_ID
          FROM DUAL;
    END IF;

    IF :NEW.SZRSFBP_ACTIVITY_DATE IS NULL THEN
        :NEW.SZRSFBP_ACTIVITY_DATE := SYSDATE;
    END IF;
END;
/



CREATE OR REPLACE TRIGGER ST_SFRSTCR_SZRSFBP
BEFORE DELETE ON SFRSTCR
FOR EACH ROW
BEGIN

    INSERT INTO INTEGRACION.SZRSFBP (
        SZRSFBP_TERM_CODE,
        SZRSFBP_PIDM,
        SZRSFBP_CRN,
        SZRSFBP_ACTIVITY_DATE
    )
    SELECT
        :OLD.SFRSTCR_TERM_CODE,
        :OLD.SFRSTCR_PIDM,
        :OLD.SFRSTCR_CRN,
        SYSDATE
    FROM DUAL
    WHERE EXISTS (
        SELECT 1
          FROM ITZERST z
         WHERE z.TERM_CODE = :OLD.SFRSTCR_TERM_CODE
           AND z.PIDM      = :OLD.SFRSTCR_PIDM
           AND z.CRN       = :OLD.SFRSTCR_CRN
           AND z.STATUS    = 'PROCESSED_OK'
           AND z.OP_TYPE   = 'CREATE_ENRROLLMENT'
    );

END;
/