
  CREATE TABLE "INTEGRACION"."ITZBGSP" 
   (	"ID" NUMBER(19,0) NOT NULL ENABLE, 
	"BUSINESS_LINE" VARCHAR2(50 BYTE), 
	"REQUEST" CLOB, 
	"RESPONSE" CLOB, 
	"CREATE_DATE" TIMESTAMP (6) DEFAULT SYSTIMESTAMP, 
	"REQUEST_DATE" TIMESTAMP (6), 
	"RESPONSE_DATE" TIMESTAMP (6), 
	"OP_TYPE" VARCHAR2(100 BYTE), 
	"STATUS" VARCHAR2(100 BYTE), 
	"STATUS_RESPONSE" VARCHAR2(100 BYTE), 
	"PIDM" NUMBER(8,0), 
	"ID_SPRIDEN" VARCHAR2(9 CHAR), 
	 CONSTRAINT "PK_ITZBGSP" PRIMARY KEY ("ID"),
	 CONSTRAINT "JSON_CHECK_REQ" CHECK (REQUEST IS JSON) ENABLE, 
	 CONSTRAINT "JSON_CHECK_RES" CHECK (RESPONSE IS JSON) ENABLE
   ) ;

   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."ID" IS 'Identificador secuencial autogenerado.';
   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."BUSINESS_LINE" IS 'Línea de negocio: ONLINE, FLEX o CYP.';
   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."REQUEST" IS 'JSON enviado al servicio.';
   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."RESPONSE" IS 'JSON recibido como respuesta del servicio.';
   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."CREATE_DATE" IS 'Fecha de creación del registro.';
   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."REQUEST_DATE" IS 'Fecha y hora de envío de la solicitud.';
   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."RESPONSE_DATE" IS 'Fecha y hora de recepción de la respuesta.';
   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."OP_TYPE" IS 'Tipo de operación: CREATE_TERM, UPD_TERM, CREATE_USER, UPD_USER, DEL_USUARIO, CREATE_NRC, UPD_NRC, ENROLLMENT_TEACHER, ENRROLLMENT_STUDENT.';
   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."STATUS" IS 'Estado del procesamiento: PENDING(Banner), PROCESSING(.NET), PROCESSED(.NET), COMPLETED(Banner), FAIL(.NET/Banner).';
   COMMENT ON COLUMN "INTEGRACION"."ITZBGSP"."STATUS_RESPONSE" IS 'Estado de procesamiento del response en Banner';
   COMMENT ON TABLE "INTEGRACION"."ITZBGSP"  IS 'Bitácora de integración entre Banner y servicios .NET.';

  CREATE INDEX "BANINST1"."ITZBGSP_BUSINESS_LINE_IDX" ON "INTEGRACION"."ITZBGSP" ("BUSINESS_LINE") ;

  CREATE INDEX "BANINST1"."ITZBGSP_CREATE_DATE_IDX" ON "INTEGRACION"."ITZBGSP" ("CREATE_DATE")    ;

  CREATE OR REPLACE EDITIONABLE TRIGGER "INTEGRACION"."ST_ITZBGSP_PRGNREP" 
AFTER INSERT OR UPDATE OR DELETE
ON integracion.itzbgsp
FOR EACH ROW
BEGIN
   IF INSERTING THEN

      INSERT INTO prgnrep.ivzbgsp
      (
         ID,
         BUSINESS_LINE,
         REQUEST,
         RESPONSE,
         CREATE_DATE,
         REQUEST_DATE,
         RESPONSE_DATE,
         OP_TYPE,
         STATUS,
         PIDM,
         ID_SPRIDEN
         
      )
      VALUES
      (
         :NEW.ID,
         :NEW.BUSINESS_LINE,
         :NEW.REQUEST,
         :NEW.RESPONSE,
         :NEW.CREATE_DATE,
         :NEW.REQUEST_DATE,
         :NEW.RESPONSE_DATE,
         :NEW.OP_TYPE,
         :NEW.STATUS,
         :NEW.PIDM,
         :NEW.ID_SPRIDEN
      );

   ELSIF UPDATING THEN

      UPDATE prgnrep.ivzbgsp
         SET BUSINESS_LINE = :NEW.BUSINESS_LINE,
             REQUEST       = :NEW.REQUEST,
             RESPONSE      = :NEW.RESPONSE,
             CREATE_DATE   = :NEW.CREATE_DATE,
             REQUEST_DATE  = :NEW.REQUEST_DATE,
             RESPONSE_DATE = :NEW.RESPONSE_DATE,
             OP_TYPE       = :NEW.OP_TYPE,
             STATUS        = :NEW.STATUS,
             PIDM          = :NEW.PIDM,
             ID_SPRIDEN    = :NEW.ID_SPRIDEN
       WHERE ID = :NEW.ID;

   ELSIF DELETING THEN

      DELETE
        FROM prgnrep.ivzbgsp
       WHERE ID = :OLD.ID;

   END IF;
END;
/
ALTER TRIGGER "INTEGRACION"."ST_ITZBGSP_PRGNREP" ENABLE;

